-- 88: เปิดแคมเปญ "เช็คอิน 7 วัน รับชุดลิมิเต็ดราชันธาตุ" ทันที (เริ่มวันที่รันไฟล์นี้ นาน 7 วัน) · ต้องรัน SQL 87 ก่อน
--  ขั้นรางวัล: ครบ 3 วัน = 30 EXP + 20 เหรียญ · ครบ 5 วัน = 50 EXP + 50 เหรียญ + ตั๋วกาชา 1 · ครบ 7 วัน = 100 EXP + 100 เหรียญ + ตั๋ว 2 + ชุดราชันธาตุ 3 ชิ้น
--  รันซ้ำได้: ถ้ามีแคมเปญชื่อเดียวกันที่ยังเปิดอยู่แล้วจะไม่สร้างซ้ำ · ปิด/ลบ/แก้ได้ที่แอดมิน 🎟️ เช็คอิน
-- =====================================================================
do $$
declare cid uuid;
begin
  if exists (select 1 from checkin_camps where title = 'เช็คอิน 7 วัน รับชุดลิมิเต็ดราชันธาตุ' and not closed and end_day >= today_th()) then
    raise notice 'มีแคมเปญนี้เปิดอยู่แล้ว ไม่สร้างซ้ำ'; return;
  end if;
  insert into checkin_camps (title, message, start_day, end_day)
  values ('เช็คอิน 7 วัน รับชุดลิมิเต็ดราชันธาตุ', 'เข้าแอปเช็คอินวันละครั้ง ยิ่งครบหลายวันยิ่งได้รางวัลมาก — ครบ 7 วันรับชุดลิมิเต็ด 3 ชิ้น!', today_th(), today_th() + 6)
  returning id into cid;
  insert into checkin_miles (camp_id, need, exp, coins, pulls, set_key) values
    (cid, 3, 30, 20, 0, null),
    (cid, 5, 50, 50, 1, null),
    (cid, 7, 100, 100, 2, 'lim_king1');
end $$;
