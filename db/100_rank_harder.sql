-- 100: เพิ่มความยากในการขึ้นแรงค์ช่วงหลัง (Emerald → Challenger ใช้ EXP มากขึ้นเป็นขั้น)
-- ต้องรันหลัง 25 · รันซ้ำได้ · เปลี่ยนเฉพาะแรงค์ที่ยังเป็นค่าจาก SQL 25 (ถ้าครูแก้ค่าเองไว้จะไม่ทับ)
-- เกณฑ์ EXP เดิม → ใหม่ (ช่วง EXP ที่ต้องเก็บเพิ่มต่อขั้น: 1,100 → 1,500 → 1,900 → 2,400 → 3,300 เดิม 900 → 1,200 → 1,500 → 1,800 → 2,300)
--   Emerald 2,700 → 2,900 · Diamond 3,900 → 4,400 · Master 5,400 → 6,300 · Grandmaster 7,200 → 8,700 · Challenger 9,500 → 12,000
-- Bronze–Platinum ไม่เปลี่ยน (นักเรียนใหม่ขึ้นเร็วเหมือนเดิม)
-- หมายเหตุ: นักเรียนที่ EXP อยู่ระหว่างเกณฑ์เก่า–ใหม่ จะถูกลดแรงค์ที่แสดงลงตามเกณฑ์ใหม่ (EXP ไม่หาย)
update ch_ranks r set min_exp = v.new_exp
  from (values ('emerald',2700,2900),('diamond',3900,4400),('master',5400,6300),('grandmaster',7200,8700),('challenger',9500,12000)) v(key, old_exp, new_exp)
 where r.key = v.key and r.min_exp = v.old_exp;
